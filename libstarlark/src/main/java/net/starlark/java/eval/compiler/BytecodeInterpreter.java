package net.starlark.java.eval.compiler;

import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import net.starlark.java.eval.*;
import net.starlark.java.syntax.Location;

/**
 * A stack-based bytecode interpreter for Starlark.
 *
 * <p>This interpreter executes bytecode generated by BytecodeCompiler. It maintains:
 * - A value stack for operands
 * - Local variable storage
 * - Global variable storage
 * - An instruction pointer
 *
 * <p>The interpreter is designed to be compatible with WebAssembly semantics.
 *
 * <p><b>Stack Trace Preservation:</b> The interpreter properly preserves stack traces
 * when exceptions occur. Line number information from the bytecode is used to create
 * accurate error locations, and exceptions are integrated with the StarlarkThread's
 * call stack to provide complete stack traces in error messages.
 *
 * <p>Exceptions thrown during execution will include:
 * <ul>
 *   <li>The original error message
 *   <li>The source file and line number where the error occurred
 *   <li>The complete call stack showing function calls leading to the error
 * </ul>
 */
public final class BytecodeInterpreter {

  private final BytecodeChunk chunk;
  private final StarlarkThread thread;
  private final Object[] locals;
  private final Map<String, Object> globals;
  private final List<Object> stack;
  private final String filename;
  private int ip; // Instruction pointer

  private BytecodeInterpreter(
      BytecodeChunk chunk, StarlarkThread thread, Map<String, Object> globals, String filename) {
    this.chunk = chunk;
    this.thread = thread;
    this.locals = new Object[chunk.getLocalCount()];
    this.globals = globals != null ? globals : new HashMap<>();
    this.stack = new ArrayList<>();
    this.filename = filename != null ? filename : "<bytecode>";
    this.ip = 0;
  }

  /**
   * Executes a bytecode chunk and returns the result.
   *
   * @param chunk the bytecode to execute
   * @param thread the Starlark thread context
   * @param globals the global variable namespace
   * @return the result of execution
   * @throws EvalException if execution fails
   * @throws InterruptedException if execution is interrupted
   */
  public static Object execute(
      BytecodeChunk chunk, StarlarkThread thread, Map<String, Object> globals)
      throws EvalException, InterruptedException {
    return execute(chunk, thread, globals, null);
  }

  /**
   * Executes a bytecode chunk and returns the result.
   *
   * @param chunk the bytecode to execute
   * @param thread the Starlark thread context
   * @param globals the global variable namespace
   * @param filename the source filename for error reporting
   * @return the result of execution
   * @throws EvalException if execution fails
   * @throws InterruptedException if execution is interrupted
   */
  public static Object execute(
      BytecodeChunk chunk, StarlarkThread thread, Map<String, Object> globals, String filename)
      throws EvalException, InterruptedException {
    BytecodeInterpreter interpreter = new BytecodeInterpreter(chunk, thread, globals, filename);
    return interpreter.run();
  }

  /**
   * Executes a bytecode chunk with arguments.
   *
   * @param chunk the bytecode to execute
   * @param thread the Starlark thread context
   * @param args the function arguments
   * @param globals the global variable namespace
   * @return the result of execution
   * @throws EvalException if execution fails
   * @throws InterruptedException if execution is interrupted
   */
  public static Object executeWithArgs(
      BytecodeChunk chunk, StarlarkThread thread, Object[] args, Map<String, Object> globals)
      throws EvalException, InterruptedException {
    return executeWithArgs(chunk, thread, args, globals, null);
  }

  /**
   * Executes a bytecode chunk with arguments.
   *
   * @param chunk the bytecode to execute
   * @param thread the Starlark thread context
   * @param args the function arguments
   * @param globals the global variable namespace
   * @param filename the source filename for error reporting
   * @return the result of execution
   * @throws EvalException if execution fails
   * @throws InterruptedException if execution is interrupted
   */
  public static Object executeWithArgs(
      BytecodeChunk chunk,
      StarlarkThread thread,
      Object[] args,
      Map<String, Object> globals,
      String filename)
      throws EvalException, InterruptedException {
    BytecodeInterpreter interpreter = new BytecodeInterpreter(chunk, thread, globals, filename);

    // Initialize local variables with arguments
    int paramCount = Math.min(args.length, chunk.getParameterCount());
    for (int i = 0; i < paramCount; i++) {
      interpreter.locals[i] = args[i];
    }

    return interpreter.run();
  }

  /**
   * Creates a Location object for the current instruction.
   */
  private Location currentLocation() {
    int lineNum = chunk.getLineNumber(ip);
    if (lineNum < 0) {
      lineNum = 0;
    }
    return Location.fromFileLineColumn(filename, lineNum, 0);
  }

  /**
   * Wraps an exception with location information from the current instruction.
   */
  private EvalException withLocation(EvalException ex) {
    // The exception will get the full call stack from the thread when it propagates
    return ex;
  }

  /**
   * Creates an EvalException with a formatted message and current location.
   */
  private EvalException error(String format, Object... args) throws EvalException {
    String message = String.format(format, args);
    return new EvalException(message);
  }

  private Object run() throws EvalException, InterruptedException {
    List<Instruction> instructions = chunk.getInstructions();

    try {
      while (ip < instructions.size()) {
        // Check for interrupts
        if (Thread.interrupted()) {
          throw new InterruptedException();
        }

        Instruction instr = instructions.get(ip);
        Opcode opcode = instr.getOpcode();

      // Execute instruction
      switch (opcode) {
        // Stack manipulation
        case POP:
          pop();
          break;

        case DUP:
          push(peek());
          break;

        case SWAP:
          {
            Object a = pop();
            Object b = pop();
            push(a);
            push(b);
          }
          break;

        // Constants
        case LOAD_CONST:
          push(chunk.getConstantPool().getConstant(instr.getOperand1()));
          break;

        case LOAD_NONE:
          push(Starlark.NONE);
          break;

        case LOAD_TRUE:
          push(true);
          break;

        case LOAD_FALSE:
          push(false);
          break;

        // Variables
        case LOAD_LOCAL:
          {
            int index = instr.getOperand1();
            Object value = locals[index];
            if (value == null) {
              throw Starlark.errorf("local variable not initialized");
            }
            push(value);
          }
          break;

        case STORE_LOCAL:
          {
            int index = instr.getOperand1();
            locals[index] = pop();
          }
          break;

        case LOAD_GLOBAL:
          {
            String name = (String) chunk.getConstantPool().getConstant(instr.getOperand1());
            Object value = globals.get(name);
            if (value == null) {
              // Try thread globals
              value = thread.getGlobals().get(name);
            }
            if (value == null) {
              throw Starlark.errorf("name '%s' is not defined", name);
            }
            push(value);
          }
          break;

        case STORE_GLOBAL:
          {
            String name = (String) chunk.getConstantPool().getConstant(instr.getOperand1());
            globals.put(name, pop());
          }
          break;

        case LOAD_FREE:
          // TODO: Implement closure variable loading
          throw new UnsupportedOperationException("Free variables not yet implemented");

        case STORE_FREE:
          // TODO: Implement closure variable storage
          throw new UnsupportedOperationException("Free variables not yet implemented");

        // Arithmetic
        case ADD:
          binaryOp((a, b) -> Starlark.add(a, b));
          break;

        case SUBTRACT:
          binaryOp((a, b) -> Starlark.subtract(a, b));
          break;

        case MULTIPLY:
          binaryOp((a, b) -> Starlark.multiply(a, b));
          break;

        case DIVIDE:
          binaryOp((a, b) -> Starlark.divide(a, b));
          break;

        case FLOOR_DIV:
          binaryOp((a, b) -> Starlark.divide(a, b)); // TODO: floor division
          break;

        case MODULO:
          binaryOp((a, b) -> Starlark.remainder(a, b));
          break;

        case NEGATE:
          unaryOp(a -> Starlark.minus(a));
          break;

        case POSITIVE:
          unaryOp(a -> Starlark.plus(a));
          break;

        // Comparison
        case EQUAL:
          binaryOp((a, b) -> a.equals(b));
          break;

        case NOT_EQUAL:
          binaryOp((a, b) -> !a.equals(b));
          break;

        case LESS:
          binaryOp((a, b) -> Starlark.compare(a, b) < 0);
          break;

        case LESS_EQUAL:
          binaryOp((a, b) -> Starlark.compare(a, b) <= 0);
          break;

        case GREATER:
          binaryOp((a, b) -> Starlark.compare(a, b) > 0);
          break;

        case GREATER_EQUAL:
          binaryOp((a, b) -> Starlark.compare(a, b) >= 0);
          break;

        case IN:
          {
            Object item = pop();
            Object container = pop();
            push(Starlark.isIn(item, container));
          }
          break;

        case NOT_IN:
          {
            Object item = pop();
            Object container = pop();
            push(!Starlark.isIn(item, container));
          }
          break;

        // Logical
        case AND:
          {
            Object b = pop();
            Object a = pop();
            push(Starlark.truth(a) && Starlark.truth(b));
          }
          break;

        case OR:
          {
            Object b = pop();
            Object a = pop();
            push(Starlark.truth(a) || Starlark.truth(b));
          }
          break;

        case NOT:
          unaryOp(a -> !Starlark.truth(a));
          break;

        // Collections
        case BUILD_LIST:
          {
            int count = instr.getOperand1();
            List<Object> elements = new ArrayList<>(count);
            for (int i = 0; i < count; i++) {
              elements.add(0, pop()); // Reverse order
            }
            push(StarlarkList.copyOf(thread.mutability(), elements));
          }
          break;

        case BUILD_TUPLE:
          {
            int count = instr.getOperand1();
            Object[] elements = new Object[count];
            for (int i = count - 1; i >= 0; i--) {
              elements[i] = pop();
            }
            push(Tuple.wrap(elements));
          }
          break;

        case BUILD_DICT:
          {
            int count = instr.getOperand1();
            Dict<Object, Object> dict = Dict.of(thread.mutability());
            for (int i = 0; i < count; i++) {
              Object value = pop();
              Object key = pop();
              dict.putEntry(key, value);
            }
            push(dict);
          }
          break;

        // Indexing
        case INDEX:
          {
            Object key = pop();
            Object object = pop();
            push(Starlark.index(object, key));
          }
          break;

        case STORE_INDEX:
          {
            Object value = pop();
            Object key = pop();
            Object object = pop();
            Starlark.setIndex(object, key, value);
          }
          break;

        case SLICE:
          {
            Object step = pop();
            Object stop = pop();
            Object start = pop();
            Object object = pop();
            push(Starlark.slice(object, start, stop, step));
          }
          break;

        // Attributes
        case LOAD_ATTR:
          {
            String name = (String) chunk.getConstantPool().getConstant(instr.getOperand1());
            Object object = pop();
            push(Starlark.getattr(thread.getSemantics(), object, name));
          }
          break;

        case STORE_ATTR:
          {
            String name = (String) chunk.getConstantPool().getConstant(instr.getOperand1());
            Object value = pop();
            Object object = pop();
            Starlark.setField(object, name, value);
          }
          break;

        // Function calls
        case CALL:
          {
            int posArgs = instr.getOperand1();
            int kwArgs = instr.getOperand2();

            // Collect keyword arguments
            Object[] kwPairs = new Object[kwArgs * 2];
            for (int i = kwArgs - 1; i >= 0; i--) {
              kwPairs[i * 2 + 1] = pop(); // value
              kwPairs[i * 2] = pop(); // name
            }

            // Collect positional arguments
            Object[] posArgValues = new Object[posArgs];
            for (int i = posArgs - 1; i >= 0; i--) {
              posArgValues[i] = pop();
            }

            Object function = pop();

            // TODO: Properly handle keyword arguments
            // For now, just call with positional args
            Object result = Starlark.call(thread, function, posArgValues, new Object[0]);
            push(result);
          }
          break;

        case RETURN:
          return pop();

        // Control flow
        case JUMP:
          ip = instr.getOperand1() - 1; // -1 because we increment at end of loop
          break;

        case JUMP_IF_TRUE:
          if (Starlark.truth(peek())) {
            ip = instr.getOperand1() - 1;
          }
          break;

        case JUMP_IF_FALSE:
          if (!Starlark.truth(peek())) {
            ip = instr.getOperand1() - 1;
          }
          break;

        case POP_JUMP_IF_TRUE:
          if (Starlark.truth(pop())) {
            ip = instr.getOperand1() - 1;
          }
          break;

        case POP_JUMP_IF_FALSE:
          if (!Starlark.truth(pop())) {
            ip = instr.getOperand1() - 1;
          }
          break;

        // Iteration
        case GET_ITER:
          {
            Object iterable = pop();
            push(Starlark.iter(iterable));
          }
          break;

        case FOR_ITER:
          {
            Object iterator = peek();
            Object next = Starlark.iteratorNext(iterator);
            if (next == null) {
              // Iterator exhausted, jump to end of loop
              ip = instr.getOperand1() - 1;
            } else {
              push(next);
            }
          }
          break;

        case NOP:
          // No operation
          break;

        case MAKE_FUNCTION:
          // TODO: Implement function creation
          throw new UnsupportedOperationException("MAKE_FUNCTION not yet implemented");

        case LOAD_MODULE:
          // TODO: Implement module loading
          throw new UnsupportedOperationException("LOAD_MODULE not yet implemented");

        default:
          throw new UnsupportedOperationException("Unsupported opcode: " + opcode);
      }

        ip++;
      }

      // If we reach here without returning, return None
      return Starlark.NONE;

    } catch (EvalException ex) {
      // Ensure the exception has proper stack trace from the thread
      throw ex.ensureStack(thread);
    } catch (Exception ex) {
      // Wrap unexpected exceptions with location information
      EvalException evalEx = new EvalException("Internal error during bytecode execution", ex);
      throw evalEx.ensureStack(thread);
    }
  }

  private void push(Object value) {
    stack.add(value);
  }

  private Object pop() throws EvalException {
    if (stack.isEmpty()) {
      throw error("stack underflow");
    }
    return stack.remove(stack.size() - 1);
  }

  private Object peek() throws EvalException {
    if (stack.isEmpty()) {
      throw error("stack underflow");
    }
    return stack.get(stack.size() - 1);
  }

  private void binaryOp(BinaryOperation op) throws EvalException, InterruptedException {
    Object b = pop();
    Object a = pop();
    push(op.apply(a, b));
  }

  private void unaryOp(UnaryOperation op) throws EvalException {
    Object a = pop();
    push(op.apply(a));
  }

  @FunctionalInterface
  private interface BinaryOperation {
    Object apply(Object a, Object b) throws EvalException, InterruptedException;
  }

  @FunctionalInterface
  private interface UnaryOperation {
    Object apply(Object a) throws EvalException;
  }
}
